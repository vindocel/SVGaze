await fs.mkdir(path.join(vendor, 'licenses'), { recursive: true });
const seen = new Set(),
  inventory = [];
async function preserve(name, parent = path.join(root, 'package.json')) {
  const require = createRequire(parent);
  let location;
  try {
    location = path.dirname(require.resolve(name + '/package.json'));
  } catch {
    location = path.dirname(require.resolve(name));
    while (
      !(await fs.stat(path.join(location, 'package.json')).then(
        () => true,
        () => false,
      ))
    ) {
      const next = path.dirname(location);
      if (next === location) throw new Error('Package metadata not found: ' + name);
      location = next;
    }
  }
  if (seen.has(location)) return;
  seen.add(location);
  const info = JSON.parse(await fs.readFile(path.join(location, 'package.json'), 'utf8'));
  inventory.push({ name: info.name, version: info.version, license: info.license });
  for (const file of await fs.readdir(location))
    if (/^(license|licence|copying|notice)(\..*)?$/i.test(file))
      await fs.copyFile(
        path.join(location, file),
        path.join(
          vendor,
          'licenses',
          info.name.replace('/', '-').replace('@', '') + '-' + info.version + '-' + file + '.txt',
        ),
      );
  for (const dependency of Object.keys(info.dependencies || {}))
    await preserve(dependency, path.join(location, 'package.json'));
}
for (const name of ['svgo', '@lezer/xml', 'fflate', 'codemirror', 'prismjs']) await preserve(name);
inventory.sort((a, b) => a.name.localeCompare(b.name));
await fs.writeFile(
  path.join(vendor, 'THIRD_PARTY_NOTICES.md'),
  '# Browser dependencies\n\nGenerated by `npm run vendor`. Licenses are preserved in `licenses/`. This inventory includes declared transitive packages, some of which the browser build removes.\n\n' +
    inventory
      .map((p) => `- ${p.name} ${p.version} — ${p.license || 'See license file'}`)
      .join('\n') +
    '\n',
);
